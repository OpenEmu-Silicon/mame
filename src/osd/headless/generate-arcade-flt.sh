#!/usr/bin/env bash
# Regenerate src/mame/arcade.flt for the OpenEmu headless arcade build.
#
# MAME removed its arcade subtarget in 0.253. This rebuilds the equivalent
# driver filter from every driver source that declares arcade machines with
# the GAME/GAMEL macros (optionally preceded by a /* ... */ comment).
# Re-run after updating to a new MAME version.

set -euo pipefail

MAME_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
OUT="$MAME_DIR/src/mame/arcade.flt"

# Sources that makedep.py can't discover from #include lines (it only pairs a
# header with same-named .cpp files), but that the drivers above need to link.
EXTRA_SOURCES=(
	"cave/cv1k_v_blit*.cpp"
)

cd "$MAME_DIR/src/mame"

{
	echo "// Arcade driver filter for the OpenEmu headless build."
	echo "// Generated by src/osd/headless/generate-arcade-flt.sh - do not edit by hand."
	echo
	grep -rlE --include='*.cpp' '^[[:space:]]*(/\*.*\*/[[:space:]]*)?GAMEL?[[:space:]]*\(' . | sed 's|^\./||' | LC_ALL=C sort
	echo
	echo "// extra sources not reachable through #include"
	printf '%s\n' "${EXTRA_SOURCES[@]}"
} > "$OUT"

echo "Wrote $(grep -c '\.cpp$' "$OUT") driver sources to $OUT"
